package exercise06;

public class Gabriel02 {
    public static void main(String[] args) {
        //    2. Escreva um programa que imprima os números pares de 0 à 50. Utilize a estrutura for.
        int i;

        System.out.println("Números pares entre 0 e 50:");

        for (i = 0; i <= 50; i += 2) System.out.println(i);
    }
}
